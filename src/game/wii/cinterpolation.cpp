// the interpolation unit 0x80032038-0x80032FD4: the Wii keeps the seven camera
// interpolation classes in one file; the methods of each pair emit interleaved
// (vector and scalar together), the scalar Update tail-calls land at the end

/**
 * @note Address: 0x80032038
 * @note Size: 0xB8
 */
Vec CVectorEaseOutInterpolation::Get()
{
	return CVec(mAxes[0].Get(), mAxes[1].Get(), mAxes[2].Get());
}

/**
 * @note Address: 0x800320F0
 * @note Size: 0xB4
 */
bool CVectorEaseOutInterpolation::Step(f32 dt)
{
	bool x = mAxes[0].Step(dt);
	bool y = mAxes[1].Step(dt);
	bool z = mAxes[2].Step(dt);
	return x && y && z;
}

