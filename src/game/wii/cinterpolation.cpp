/**
 * @note Address: 0x80032D04
 * @note Size: 0x50
 */
bool CInterpolationEaseOutDivide::Step(f32 dt)
{
	f32 last = mValue;
	if (mDivisor > 0.0f) {
		mValue = (last * (mDivisor - 1.0f) + mTarget) / mDivisor;
	}
	return (f32)fabs(mValue - last) < 0.001f;
}

