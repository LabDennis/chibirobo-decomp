void VISetRGBOverDrive(u32 level)
{
	if (overDriveLevel != level) {
		overDriveLevel = level;
		__VI3in1Changed |= VI_3IN1_OVERDRIVE;
	}
}

void __VIInit3in1(void)
{
	__VIWriteI2CRegister8(0x6A, 1);
	__VIWriteI2CRegister8(0x65, 1);
	__VISetYUVSEL(VIGetDTVStatus());
	__VIWriteI2CRegister8(0x00, 0);
	__VIWriteI2CRegister16(0x71, 0x8E8E);
	__VIWriteI2CRegister8(0x02, 7);

	cgmsWord0 = 0;
	cgmsWord1 = 0;
	cgmsWord2 = 0;
	__VISetCGMS();

	VISetWSS(0, 0, 0, 0);
	__VISetWSS();

	VISetClosedCaption(0, 0, 0, 0);
	__VISetClosedCaption();

	__VISetMacrovisionImm(mvUser);

	VISetRGBOverDrive(0);
	__VISetRGBOverDrive();

	__VIWriteI2CRegister8(0x03, 1);
	__VISetGamma1_0();
	unk219C = 0;
}
