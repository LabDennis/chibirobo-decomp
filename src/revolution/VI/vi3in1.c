static void __VIWriteI2CRegister8(u8 reg, u8 data)
{
	u8 buf[2];

	buf[0] = reg;
	buf[1] = data;
	__VISendI2CData(VI_3IN1_SLAVE_ADDR, buf, 2);
	WaitMicroTime(2);
}

static void __VIWriteI2CRegister16(u8 reg, u16 data)
{
	u8 buf[3];

	buf[0] = reg;
	buf[1] = data >> 8;
	buf[2] = data & 0xFF;
	__VISendI2CData(VI_3IN1_SLAVE_ADDR, buf, 3);
	WaitMicroTime(2);
}

static void __VISetMacrovisionImm(u8* mv)
{
	u8 buf[27];
	s32 i;

	buf[0] = 0x40;
	for (i = 1; i < 27; i++) {
		buf[i] = mv[i - 1];
	}
	__VISendI2CData(VI_3IN1_SLAVE_ADDR, buf, 27);
	WaitMicroTime(2);
}

void __VISetYUVSEL(u8 dtvStatus)
{
	u8 buf[2];
	u32 tv;
	u8 data;

	tv = *(u32*)OSPhysicalToCached(0xCC);
	switch (tv) {
	case VI_PAL:
	case VI_EURGB60:
		videoMode = VI_3IN1_OUT_PAL;
		break;
	case VI_MPAL:
		videoMode = VI_3IN1_OUT_MPAL;
		break;
	case VI_NTSC:
		videoMode = VI_3IN1_OUT_NTSC;
		break;
	default:
		videoMode = VI_3IN1_OUT_NTSC;
		break;
	}

	data   = (dtvStatus << 5) | videoMode;
	buf[0] = 0x01;
	buf[1] = data;
	__VISendI2CData(VI_3IN1_SLAVE_ADDR, buf, 2);
	WaitMicroTime(2);
}

void __VISetFilter4EURGB60(u8 enable)
{
	__VIWriteI2CRegister8(0x6E, enable);
}

void __VISetCGMS(void)
{
	u8 buf[3];

	buf[0] = 0x05;
	buf[1] = ((cgmsWord1 << 2) & 0x3C) | (cgmsWord0 & 0x03);
	buf[2] = cgmsWord2;
	__VISendI2CData(VI_3IN1_SLAVE_ADDR, buf, 3);
	WaitMicroTime(2);
}

void __VISetWSS(void)
{
	u8 buf[3];

	buf[0] = 0x08;
	buf[1] = ((wssWord1 << 4) & 0xF0) | (wssWord0 & 0x0F);
	buf[2] = ((wssWord3 << 3) & 0x38) | (wssWord2 & 0x07);
	__VISendI2CData(VI_3IN1_SLAVE_ADDR, buf, 3);
	WaitMicroTime(2);
}

void __VISetClosedCaption(void)
{
	u8 buf[5];

	buf[0] = 0x7A;
	buf[1] = ccWord0 & 0x7F;
	buf[2] = ccWord1 & 0x7F;
	buf[3] = ccWord2 & 0x7F;
	buf[4] = ccWord3 & 0x7F;
	__VISendI2CData(VI_3IN1_SLAVE_ADDR, buf, 5);
	WaitMicroTime(2);
}

