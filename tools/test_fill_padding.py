SCRIPT = Path(__file__).with_name("fill_padding.py")
SECTION_ADDRESS = 0x80001000
SECTION_OFFSET = 0x100


class LinkPaddingConfigTest(unittest.TestCase):
    def test_only_compiled_link_inputs_use_compiler_padding(self):
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        self.addCleanup(os.chdir, Path.cwd())
        os.chdir(directory.name)

        config = ProjectConfig()
        config.version = "GGTE01"
        config.linker_version = "GC/2.6"
        config.dtk_tag = config.objdiff_tag = config.sjiswrap_tag = "test"
        config.compilers_tag = config.binutils_tag = "test"
        config.config_path = Path("config.yml")
        config.check_sha_path = Path("build.sha1")
        config.asflags = []
        config.src_dir = Path.cwd() / "src"
        config.asm_dir = Path.cwd() / "asm"
        config.src_dir.mkdir()
        config.asm_dir.mkdir()
        config.generate_map = True
        config.libs = [
            {
                "lib": "audio",
                "cflags": [],
                "padding": "small_data",
                "objects": [
                    Object(True, "mix.o", source="mix.c"),
                    Object(False, "stream.o", source="stream.c"),
                    Object(True, "entry.o", source="entry.s"),
                ],
            },
            {
                "lib": "other",
                "cflags": [],
                "objects": [Object(True, "table.o", source="table.c")],
            },
        ]
        for source in ("mix.c", "stream.c", "entry.s", "table.c"):
            (config.src_dir / source).touch()
        (config.asm_dir / "stream.s").touch()

        objects = config.objects()
        build_config: BuildConfig = {
            "version": "1.0.0",
            "name": "main",
            "module_id": 0,
            "ldscript": "build/GGTE01/ldscript.lcf",
            "entry": "_start",
            "units": [
                {"name": name, "object": f"obj/{name}", "autogenerated": False}
                for name in objects
            ],
            "modules": [],
            "links": [],
        }
        generate_build_ninja(config, objects, build_config)

        manifest = config.out_path() / "main_link_inputs.json"
        self.assertEqual(
            json.loads(manifest.read_text(encoding="utf-8")),
            {
                "build/GGTE01/src/mix.o": "small_data",
                "build/GGTE01/mod/stream.o": None,
                "build/GGTE01/src/entry.o": None,
                "build/GGTE01/src/table.o": None,
            },
        )


class FillPaddingTest(unittest.TestCase):
    @staticmethod
    def make_input(path, alignment):
        # Only the ELF section table and its string table are used by the padder.
        data = bytearray(52 + 3 * 40)
        data[:6] = b"\x7fELF\x01\x02"
        struct.pack_into(">I", data, 32, 52)
        struct.pack_into(">HHH", data, 46, 40, 3, 2)
        struct.pack_into(">10I", data, 92, 1, 1, 3, 0, 0, 0, 0, 0, alignment, 0)
        names = b"\0.sdata\0.shstrtab\0"
        struct.pack_into(">10I", data, 132, 8, 3, 0, 0, len(data), len(names), 0, 0, 1, 0)
        path.write_bytes(data + names)

    def run_padding(self, data, section_size, layout, source_alignment=8):
        struct.pack_into(">I", data, 0, SECTION_OFFSET)
        struct.pack_into(">I", data, 72, SECTION_ADDRESS)
        struct.pack_into(">I", data, 144, section_size)
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            dol = root / "main.dol"
            link_map = root / "main.elf.MAP"
            inputs = root / "main_link_inputs.json"
            dol.write_bytes(data)
            link_map.write_text(".sdata section layout\n" + layout)
            source = root / "source.o"
            extracted = root / "extracted.o"
            self.make_input(source, source_alignment)
            self.make_input(extracted, 4)
            inputs.write_text(json.dumps({str(source): "small_data", str(extracted): None}))
            result = subprocess.run(
                [sys.executable, SCRIPT, dol, link_map, inputs],
                capture_output=True,
                text=True,
            )
            return result, dol.read_bytes()

    def test_aliases_do_not_split_the_enclosing_symbol(self):
        data = bytearray(SECTION_OFFSET + 0x30)
        result, output = self.run_padding(
            data,
            0x30,
            "  00000000 000030 80001000  4 .sdata \tsource.o\n"
            "  00000000 000021 80001000  4 full_object \tsource.o\n"
            "  00000004 000004 80001004  4 first_alias \tsource.o\n"
            "  00000010 000004 80001010  4 second_alias \tsource.o\n"
            "  00000024 000001 80001024  1 next_object_alias \tsource.o\n"
            "  00000024 00000c 80001024  4 next_object \tsource.o\n",
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        data[SECTION_OFFSET + 0x21 : SECTION_OFFSET + 0x24] = b"000"
        self.assertEqual(output, data)

    def test_gap_cannot_cross_a_dol_section_end(self):
        # Bytes follow the section in the file but aren't part of its address range.
        data = bytearray(SECTION_OFFSET + 0x30)
        result, output = self.run_padding(
            data,
            0x22,
            "  00000000 000030 80001000  4 .sdata \tsource.o\n"
            "  00000000 000021 80001000  4 first_object \tsource.o\n"
            "  00000024 00000c 80001024  4 next_object \tsource.o\n",
        )
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("does not fit in a file-backed DOL section", result.stderr)
        self.assertEqual(output, data)

    def test_gap_not_explained_by_symbol_alignment_is_preserved(self):
        data = bytearray(SECTION_OFFSET + 0x30)
        result, output = self.run_padding(
            data,
            0x30,
            "  00000000 000030 80001000  1 .sdata \tsource.o\n"
            "  00000000 000004 80001000  4 first_object \tsource.o\n"
            "  00000010 000020 80001010  4 next_object \tsource.o\n",
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(output, data)

    def test_gap_starts_after_extracted_objects_unnamed_tail(self):
        data = bytearray(SECTION_OFFSET + 0x30)
        result, output = self.run_padding(
            data,
            0x30,
            "  00000000 000014 80001000  1 .sdata \textracted.o\n"
            "  00000000 000004 80001000  4 known_symbol \textracted.o\n"
            "  00000018 000018 80001018  1 .sdata \tsource.o\n"
            "  00000018 000018 80001018  4 next_object \tsource.o\n",
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        data[SECTION_OFFSET + 0x14 : SECTION_OFFSET + 0x18] = b"0000"
        self.assertEqual(output, data)

    def test_gap_not_explained_by_input_section_alignment_is_preserved(self):
        data = bytearray(SECTION_OFFSET + 0x30)
        result, output = self.run_padding(
            data,
            0x30,
            "  00000000 000014 80001000  1 .sdata \textracted.o\n"
            "  00000018 000018 80001018  1 .sdata \tsource.o\n"
            "  00000018 000018 80001018  4 next_object \tsource.o\n",
            source_alignment=4,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(output, data)
