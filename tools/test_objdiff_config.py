import json
import os
from pathlib import Path
import tempfile
import unittest

from tools.project import (
    BuildConfig,
    Object,
    ProgressCategory,
    ProjectConfig,
    generate_objdiff_config,
)


class ObjdiffConfigTest(unittest.TestCase):
    def test_report_uses_the_build_objects_without_local_mappings(self):
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        self.addCleanup(os.chdir, Path.cwd())
        os.chdir(directory.name)

        config = ProjectConfig()
        config.version = "GGTE01"
        config.linker_version = "GC/2.6"
        config.progress_categories = [ProgressCategory("sdk", "SDK")]
        source = Object(
            False, "sdk/heap.o", source="sdk/heap.c", cflags=[], progress_category="sdk"
        ).resolve(config, {})
        assembly = Object(
            True, "sdk/cache.o", source="sdk/cache.s", cflags=[], progress_category="sdk"
        ).resolve(config, {})
        target = "build/GGTE01/obj/sdk/heap.o"
        assembly_target = "build/GGTE01/obj/sdk/cache.o"
        build_config: BuildConfig = {
            "version": "1.0.0",
            "name": "main",
            "module_id": 0,
            "ldscript": "build/GGTE01/ldscript.lcf",
            "entry": "_start",
            "units": [
                {"name": source.name, "object": target, "autogenerated": False},
                {"name": assembly.name, "object": assembly_target, "autogenerated": False},
            ],
            "modules": [],
            "links": [],
        }
        local_config_path = Path("objdiff.json")
        mappings = {"HeapAlloc": "HeapAllocCandidate"}
        local_config_path.write_text(
            json.dumps({"units": [{"name": "main/sdk/heap", "symbol_mappings": mappings}]}),
            encoding="utf-8",
        )

        generate_objdiff_config(
            config,
            {source.name: source, assembly.name: assembly},
            build_config,
            {(0, source.name): False, (0, assembly.name): True},
        )

        local_config = json.loads(local_config_path.read_text(encoding="utf-8"))
        report_path = config.report_project_path() / "objdiff.json"
        report = json.loads(report_path.read_text(encoding="utf-8"))
        self.assertEqual(local_config["units"][0]["symbol_mappings"], mappings)
        self.assertEqual(
            report["progress_categories"], local_config["progress_categories"]
        )
        self.assertEqual(
            report["units"],
            [
                {
                    "name": "main/sdk/heap",
                    "target_path": Path(target).absolute().as_posix(),
                    "base_path": source.src_obj_path.absolute().as_posix(),
                    "metadata": local_config["units"][0]["metadata"],
                },
                {
                    "name": "main/sdk/cache",
                    "target_path": Path(assembly_target).absolute().as_posix(),
                    "metadata": {
                        "progress_categories": ["sdk"],
                        "auto_generated": False,
                    },
                },
            ],
        )
